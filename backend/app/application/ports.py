"""Ports: what the application needs from the outside world."""
from __future__ import annotations

from datetime import date, datetime
from typing import Any, Protocol

from app.application.dto import (
    AdminOrderFilters, CartLine, GatewayResult, IssuedToken, PaymentIntent, ProductFilters, ProductInput,
    TokenClaims, VariantInfo,
)
from app.domain.entities import Order, OrderSummary, Payment, User

Row = dict[str, Any]


class Clock(Protocol):
    def now(self) -> datetime: ...  # naive UTC


class PasswordHasher(Protocol):
    def hash(self, password: str) -> str: ...
    def verify(self, password: str, hashed: str) -> bool: ...


class TokenService(Protocol):
    def issue(self, user_id: int, role: str) -> IssuedToken: ...
    def decode(self, token: str) -> TokenClaims: ...  # raises NotAuthenticated


class PaymentGateway(Protocol):
    provider: str

    def create_payment(self, order_number: str, amount_cop: int) -> PaymentIntent: ...
    def resolve(self, outcome: str) -> GatewayResult: ...


class FileStorage(Protocol):
    def save(self, content: bytes, extension: str) -> str: ...  # returns public URL


class UserRepository(Protocol):
    def add(self, user: User) -> User: ...
    def get(self, user_id: int) -> User | None: ...
    def get_by_email(self, email: str) -> User | None: ...
    def update(self, user: User, now: datetime) -> User: ...


class RevokedTokenRepository(Protocol):
    def revoke(self, jti: str, expires_at: datetime) -> None: ...
    def is_revoked(self, jti: str) -> bool: ...


class AuditLogRepository(Protocol):
    def add(self, *, user_id: int | None, action: str, path: str, ip: str | None, detail: str | None,
            now: datetime) -> None: ...


class CatalogRepository(Protocol):
    def list_categories(self) -> list[Row]: ...
    def list_colors(self) -> list[Row]: ...
    def list_sizes(self) -> list[Row]: ...
    def search_products(self, filters: ProductFilters) -> Row: ...
    def featured_products(self, limit: int) -> list[Row]: ...
    def get_product_detail(self, slug: str) -> Row | None: ...
    def get_artisan(self, artisan_id: int) -> Row | None: ...


class AdminProductRepository(Protocol):
    def list_products(self, q: str | None, status: str, page: int, page_size: int) -> Row: ...
    def get_detail(self, product_id: int) -> Row | None: ...
    def create(self, data: ProductInput, user_id: int, now: datetime) -> int: ...
    def update(self, product_id: int, data: ProductInput, user_id: int, now: datetime) -> None: ...
    def set_active(self, product_id: int, active: bool, now: datetime) -> bool: ...
    def list_categories(self) -> list[Row]: ...
    def list_artisans(self) -> list[Row]: ...


class CartRepository(Protocol):
    def get_variant(self, variant_id: int) -> VariantInfo | None: ...
    def get_variants(self, variant_ids: list[int]) -> dict[int, VariantInfo]: ...
    def list_lines(self, user_id: int) -> list[CartLine]: ...
    def find_by_variant(self, user_id: int, variant_id: int) -> CartLine | None: ...
    def get_item(self, user_id: int, item_id: int) -> CartLine | None: ...
    def set_variant_quantity(self, user_id: int, variant_id: int, quantity: int, now: datetime) -> None: ...
    def set_item_quantity(self, item_id: int, quantity: int, now: datetime) -> None: ...
    def remove_item(self, user_id: int, item_id: int, now: datetime) -> None: ...
    def clear(self, user_id: int) -> None: ...


class OrderRepository(Protocol):
    def add(self, order: Order) -> Order: ...
    def get(self, order_id: int, for_update: bool = False) -> Order | None: ...
    def list_for_user(self, user_id: int, newest_first: bool) -> list[OrderSummary]: ...
    def list_admin(self, filters: AdminOrderFilters) -> tuple[list[OrderSummary], int]: ...
    def set_status(self, order_id: int, status: str, now: datetime) -> None: ...
    def add_history(self, order_id: int, from_status: str | None, to_status: str, user_id: int | None,
                    note: str | None, now: datetime) -> None: ...


class PaymentRepository(Protocol):
    def add(self, payment: Payment, now: datetime) -> Payment: ...
    def get_by_reference(self, reference: str, for_update: bool = False) -> Payment | None: ...
    def update(self, payment: Payment, now: datetime) -> None: ...


class InventoryRepository(Protocol):
    def lock_stock(self, variant_ids: list[int]) -> dict[int, int]: ...  # SELECT ... FOR UPDATE
    def set_stock(self, variant_id: int, stock: int) -> None: ...
    def add_movement(self, *, variant_id: int, delta: int, reason: str, note: str | None, user_id: int | None,
                     order_id: int | None, now: datetime) -> None: ...
    def list_inventory(self, q: str | None, low_only: bool) -> list[Row]: ...
    def get_row(self, variant_id: int) -> Row | None: ...
    def list_movements(self, variant_id: int) -> list[Row]: ...


class ReportRepository(Protocol):
    def summary(self, date_from: date, date_to: date) -> Row: ...


class UnitOfWork(Protocol):
    users: UserRepository
    tokens: RevokedTokenRepository
    audit: AuditLogRepository
    catalog: CatalogRepository
    admin_products: AdminProductRepository
    carts: CartRepository
    orders: OrderRepository
    payments: PaymentRepository
    inventory: InventoryRepository
    reports: ReportRepository

    def __enter__(self) -> "UnitOfWork": ...
    def __exit__(self, exc_type, exc, tb) -> None: ...
    def commit(self) -> None: ...
    def rollback(self) -> None: ...


class UnitOfWorkFactory(Protocol):
    def __call__(self) -> UnitOfWork: ...
